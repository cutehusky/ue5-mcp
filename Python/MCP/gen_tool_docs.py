"""Regenerate TOOLS.md, FEATURE_MAP.md and tool_map.json from the code. Run this after adding or changing a tool."""
import asyncio
import collections
import inspect
import json
import re
import sys
from pathlib import Path

sys.argv = sys.argv[:1]
import mcp_server as m  # noqa: E402
from ue5_tools import app  # noqa: E402
from ue5_tools.catalog import CATALOG_TOOLS, CORE_TOOLS  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SOURCE = Path(__file__).resolve().parent / "ue5_tools"


def summary_of(text):
    line = next((l.strip() for l in (text or "").splitlines() if l.strip()), "")
    return line[:157].rstrip() + "..." if len(line) > 160 else line


def variants_of(fn):
    fn = inspect.unwrap(fn)
    if not fn.__closure__ or fn.__name__ in CATALOG_TOOLS:
        return None
    found = inspect.getclosurevars(fn).nonlocals.get("variants")
    return found if isinstance(found, dict) else None


def locate(module, name):
    pattern = re.compile(rf"^(?:async )?def {name}\(|^{name} = ", re.M)
    text = (SOURCE / f"{module}.py").read_text(encoding="utf-8")
    match = pattern.search(text)
    return text.count("\n", 0, match.start()) + 1 if match else 0


def main():
    listed = asyncio.run(m.mcp.list_tools())
    tools, features, groups = {}, collections.defaultdict(list), collections.defaultdict(list)

    def add(name, fn, module, kind, summary, parent=""):
        tools[name] = {"feature": module, "file": f"Python/MCP/ue5_tools/{module}.py", "line": locate(module, name), "kind": kind,
                       "core": name in CORE_TOOLS, "signature": str(inspect.signature(fn)).replace("'", ""), "summary": summary, **({"tool": parent} if parent else {})}
        features[module].append(name)

    for tool in listed:
        fn = app.mcp._tool_manager.get_tool(tool.name).fn
        variants = variants_of(fn)
        module = (next(iter(variants.values())) if variants else inspect.unwrap(fn)).__module__.split(".")[-1]
        summary = ("Variants: " + ", ".join(f"`{k}`" for k in variants)) if variants else summary_of(tool.description)
        groups[module].append((tool.name, summary.replace("|", "\\|")))
        if tool.name in CATALOG_TOOLS:
            continue  # These search the tool list; in Python use ue.find and ue.describe.
        add(tool.name, fn, module, "merged" if variants else "tool", summary)
        for variant in (variants or {}).values():
            original = inspect.unwrap(variant)
            # Keys such as "bool" are labels; a function is callable by its own name if the module exposes it.
            if original.__name__ not in tools and getattr(m, original.__name__, None) is variant:
                add(original.__name__, variant, original.__module__.split(".")[-1], "variant", summary_of(inspect.getdoc(variant)), tool.name)

    (ROOT / "tool_map.json").write_text(json.dumps({"tools": dict(sorted(tools.items()))}, indent=0) + "\n", encoding="utf-8", newline="\n")

    doc = lambda module: (inspect.getdoc(sys.modules[f"ue5_tools.{module}"]) or "").split("\n")[0]
    lines = ["# UE5_MCP tools", "", f"All {len(listed)} tools, grouped by feature module in `Python/MCP/ue5_tools/`. **Core** tools are listed to clients by default; reach the others with `find_tools` and `call_tool`, or start the server with `--all-tools`.", "",
             "Tools that show variants take a required `variant` argument.", "", "## Features", "", "| Feature | Tools |", "|---|---|"]
    lines += [f"| [{g}](#{g}) | {len(groups[g])} |" for g in sorted(groups)]
    for group in sorted(groups):
        lines += ["", f"## {group}", "", "| Tool | Core | Description |", "|---|---|---|"]
        lines += [f'| `{n}` | {"Core" if n in CORE_TOOLS or group == "catalog" else ""} | {s} |' for n, s in sorted(groups[group])]
    (ROOT / "TOOLS.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    lines = ["# Feature map", "", "Which Python file holds each feature, for scripts that call tools directly. See the `ue5-python-scripting` skill for usage.", "",
             f"`tool_map.json` lists all {len(tools)} callable functions with signature, file and line. Generated by `Python/MCP/gen_tool_docs.py`; don't edit by hand.", "",
             "| Feature | File | Functions | Covers |", "|---|---|---:|---|"]
    lines += [f"| {f} | [`{f}.py`](Python/MCP/ue5_tools/{f}.py) | {len(features[f])} | {doc(f)} |" for f in sorted(features)]
    (ROOT / "FEATURE_MAP.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(len(listed), "tools,", len(tools), "callable functions,", len(features), "features")


if __name__ == "__main__":
    main()
